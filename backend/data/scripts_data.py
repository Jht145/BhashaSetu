def devanagari_to_olchiki(text: str) -> str:
    """Converts Devanagari Santali text into authentic Ol Chiki script."""
    if not text:
        return ""
    result = []
    i = 0
    while i < len(text):
        char = text[i]
        # Check 2-char combinations if needed
        if char in DEV_TO_OL_CHIKI:
            result.append(DEV_TO_OL_CHIKI[char])
        else:
            result.append(char)
        i += 1
    return "".join(result)
